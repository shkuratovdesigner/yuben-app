"""Trim the variable fonts to the weights the site actually renders.

Newsreader is only used at 400 (regular and italic); Inter only at 400 and 500.
Pinning the weight axis keeps those weights byte-for-byte identical in rendering
(Newsreader keeps its optical-size axis), and roughly halves the font download.

Reads the @font-face rules shipped by @fontsource-variable, writes the trimmed
files to src/fonts/ and the matching rules to src/styles/fonts.css.
Re-run after upgrading either package:  python3 scripts/pin-fonts.py
"""
import re
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).resolve().parent.parent
modules = root / 'node_modules/@fontsource-variable'
out = root / 'src/fonts'
out.mkdir(exist_ok=True)

# (package, css files, weight limit, CSS font-weight descriptor)
families = [
    ('newsreader', ['opsz.css', 'opsz-italic.css'], 400, '400'),
    ('inter', ['index.css'], (400, 500), '400 500'),
]

rules = []
for package, css_files, limit, descriptor in families:
    for css_name in css_files:
        css = (modules / package / css_name).read_text()
        for body in re.findall(r'@font-face \{(.*?)\}', css, re.S):
            file_name = re.search(r'files/([\w.-]+\.woff2)', body).group(1)
            font = TTFont(modules / package / 'files' / file_name)
            trimmed = instantiateVariableFont(font, {'wght': limit})
            trimmed.flavor = 'woff2'
            target = out / file_name.replace('.woff2', '-trim.woff2')
            trimmed.save(target)
            body = re.sub(r'font-weight: [^;]+;', f'font-weight: {descriptor};', body)
            body = re.sub(r'src: [^;]+;', f"src: url('../fonts/{target.name}') format('woff2');", body)
            rules.append('@font-face {' + body + '}')
            print(f'{file_name}: {(modules / package / "files" / file_name).stat().st_size} -> {target.stat().st_size}')

header = '/* Generated by scripts/pin-fonts.py. Do not edit by hand. */\n'
(root / 'src/styles/fonts.css').write_text(header + '\n\n'.join(rules) + '\n')
